export interface StandupQuestion {
  // Тема/питання для жарту — показується на екрані стріму.
  text: string;
  // Опційна ремарка для ведучого (на екрані під питанням не показується).
  note?: string;
}

export interface QuizQuestion {
  // Текст питання — показується на сторінці стріму (в бот не надсилається).
  text: string;
  // Прийнятні відповіді. Порівняння нечутливе до регістру, пунктуації, зайвих
  // пробілів, апострофів і ё/е — тож дублювати такі варіанти не треба.
  // Перша відповідь вважається еталонною (її бачить ведучий на своїй сторінці).
  answers: string[];
  // Опційна підказка/пояснення — показується ведучому і на екрані після закриття питання.
  note?: string;
}

